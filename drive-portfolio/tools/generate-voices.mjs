/*
 * Generates the island's voice clips with ElevenLabs.
 *   ELEVENLABS_API_KEY=... node tools/generate-voices.mjs        (from the drive-portfolio folder)
 * - Library voices are added to the account one at a time, used, then removed again (free plans have 3 voice slots).
 * - Existing clips are skipped, so it can be re-run safely; delete a file to regenerate it.
 * - Writes audio/voices/*.mp3 and js/voices.js (the manifest the game reads). The key is never written anywhere.
 */
import { buildJobs, SPEAKERS, SHOP_SPEAKER, ISLANDER_LINES } from './voice-script.mjs';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const KEY = process.env.ELEVENLABS_API_KEY;
if (!KEY) { console.error('Set ELEVENLABS_API_KEY first.'); process.exit(1); }
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'audio', 'voices');
mkdirSync(OUT, { recursive: true });
const API = 'https://api.elevenlabs.io/v1';
const H = { 'xi-api-key': KEY, 'Content-Type': 'application/json' };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function api(path, opts = {}) {
  for (let attempt = 0; attempt < 4; attempt++) {
    const res = await fetch(API + path, { ...opts, headers: { ...H, ...(opts.headers || {}) } });
    if (res.status === 429 || res.status >= 500) { await sleep(1500 * (attempt + 1)); continue; }
    return res;
  }
  throw new Error('ElevenLabs is not responding: ' + path);
}

const jobs = buildJobs();
const todo = jobs.filter((j) => !existsSync(join(OUT, j.file + '.mp3')));
const chars = todo.reduce((n, j) => n + j.text.length, 0);
console.log(`${jobs.length} clips in the script · ${todo.length} to generate · ${chars} characters`);

const bySpeaker = {};
for (const j of todo) (bySpeaker[j.speaker] ||= []).push(j);
let libraryAllowed = process.env.VOICE_SET !== 'premade';   // falls back to built-in voices automatically on the free plan
const used = {};
async function tts(vid, j, S) {
  return api(`/text-to-speech/${vid}?output_format=mp3_44100_64`, {
    method: 'POST', headers: { Accept: 'audio/mpeg' },
    body: JSON.stringify({ text: j.text, model_id: 'eleven_multilingual_v2',
      voice_settings: { stability: 0.42, similarity_boost: 0.8, style: S.style, use_speaker_boost: true } }),
  });
}
for (const [sp, list] of Object.entries(bySpeaker)) {
  const S = SPEAKERS[sp];
  let vid = null, addedId = null;
  if (libraryAllowed) {
    const add = await api(`/voices/add/${S.lib[1]}/${S.lib[0]}`, { method: 'POST', body: JSON.stringify({ new_name: `Island ${S.name} (${sp})` }) });
    const added = await add.json().catch(() => ({}));
    if (add.ok && added.voice_id) {
      const probe = await tts(added.voice_id, list[0], S);
      if (probe.status === 402 || probe.status === 403) { libraryAllowed = false; await api(`/voices/${added.voice_id}`, { method: 'DELETE' }); console.log('Library voices need a paid plan here: using built-in voices.'); }
      else { vid = addedId = added.voice_id; list[0].probe = probe; }
    } else { libraryAllowed = false; console.log('Could not add library voices: using built-in voices.'); }
  }
  if (!vid) vid = S.premade;
  used[sp] = addedId ? `library:${S.name}` : `premade:${S.premade}`;
  console.log(`\n🎙  ${sp} — ${addedId ? S.name + ' (Indian-English library voice)' : 'built-in voice ' + S.premade} · ${list.length} clips`);
  try {
    for (const j of list) {
      const res = j.probe || await tts(vid, j, S);
      if (!res.ok) { console.error(`  ✗ ${j.key}: ${res.status} ${await res.text()}`); process.exitCode = 1; continue; }
      writeFileSync(join(OUT, j.file + '.mp3'), Buffer.from(await res.arrayBuffer()));
      console.log(`  ✓ ${j.file}.mp3  “${j.text}”`);
    }
  } finally {
    if (addedId) await api(`/voices/${addedId}`, { method: 'DELETE' });   // free the slot for the next speaker
  }
}

// manifest for the game: key -> { src, text }, plus who speaks for each shop
const lines = {};
for (const j of jobs) if (existsSync(join(OUT, j.file + '.mp3'))) lines[j.key] = { src: `audio/voices/${j.file}.mp3`, text: j.text };
writeFileSync(join(ROOT, 'js', 'voices.js'),
  `/* Generated by tools/generate-voices.mjs — voice clips (ElevenLabs) the game plays. Do not edit by hand. */\n` +
  `window.VOICES = ${JSON.stringify({ lines, shopSpeaker: SHOP_SPEAKER, islander: ISLANDER_LINES }, null, 1)};\n`);
console.log(`\nWrote js/voices.js with ${Object.keys(lines).length} clips.`);
